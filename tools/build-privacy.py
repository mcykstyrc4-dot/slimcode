def P(*items):
    return '\n'.join('      <p>%s</p>' % t for t in items)


def L(*items):
    """Список без вводной строки: пункт перечня уже задан абзацем выше."""
    return ('      <ul class="doc__dash">\n'
            + '\n'.join('        <li>%s</li>' % i for i in items)
            + '\n      </ul>')


def UL(intro, *items):
    out = '      <p>%s</p>\n' % intro
    out += '      <ul class="doc__dash">\n'
    out += '\n'.join('        <li>%s</li>' % i for i in items)
    out += '\n      </ul>'
    return out


